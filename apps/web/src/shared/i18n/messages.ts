export const MESSAGES = { en, fa } as const;
export type LocaleKey = keyof typeof MESSAGES;

export function translate(locale: LocaleKey, key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = MESSAGES[locale][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
